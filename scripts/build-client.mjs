/**
 * `scripts/build-client.mjs`
 * Compiles lib/paths.js, src/settings.js, and src/client.body.js
 * into the single-file runtime bundle lib/client.js for Cordis/DSH ModuleLoader.
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, '..');

const pathsJsPath = path.join(rootDir, 'lib', 'paths.js');
const settingsJsPath = path.join(rootDir, 'src', 'settings.js');
const clientBodyJsPath = path.join(rootDir, 'src', 'client.body.js');
const clientJsPath = path.join(rootDir, 'lib', 'client.js');

let pathsCode = fs.readFileSync(pathsJsPath, 'utf8');
let settingsCode = fs.readFileSync(settingsJsPath, 'utf8');
let clientBodyCode = fs.readFileSync(clientBodyJsPath, 'utf8');

// Strip top-level export statements from pathsCode and settingsCode so they become in-scope declarations
pathsCode = pathsCode
  .replace(/\bexport\s+const\s+/g, 'const ')
  .replace(/\bexport\s+function\s+/g, 'function ')
  .replace(/\bexport\s+default\s+/g, '');

settingsCode = settingsCode
  .replace(/\bexport\s+const\s+/g, 'var ')
  .replace(/\bexport\s+function\s+/g, 'function ')
  .replace(/\bexport\s+default\s+/g, '');

const bundle = `/* dsh-file-view — client half: clickable file references + accent colour.
 *
 * Two capabilities share one accent colour:
 *
 *   1. Every file path the assistant mentions in a settled message becomes a
 *      clickable inline span. Click previews it in the right sidebar,
 *      Ctrl+click hands it to the system default application, Alt+click
 *      reveals it in the file manager.
 *   2. A settings page picks that accent, which is applied through
 *      \`ctx.theme.overrideTokens\` so the Harness UI accent and the link
 *      colour move together.
 *
 * Automatically generated by scripts/build-client.mjs. Do not edit directly!
 */
window.__ModuleLoader__.load({
  id: 'dsh-file-view',
  factory: function (require) {
    var module = { exports: {} };
    var exports = module.exports;

    var react = require('react');
    var h = react.createElement;

    // ── 内联自 lib/paths.js ──────────────────────────────────────────
${pathsCode.split('\n').map(l => '    ' + l).join('\n')}

    // ── 内联自 src/settings.js ──────────────────────────────────────────
${settingsCode.split('\n').map(l => '    ' + l).join('\n')}

    var FileLinkSettings = createFileLinkSettings(react, {
      fileLinkConfig: fileLinkConfig,
      subscribeConfig: subscribeConfig,
      updateFileLinkConfig: updateFileLinkConfig,
      accentColorOf: accentColorOf
    });

    // ── 内联自 src/client.body.js ──────────────────────────────────────────
${clientBodyCode.split('\n').map(l => '    ' + l).join('\n')}

    exports.name = 'dsh-file-view';
    exports.inject = inject;
    exports.apply = apply;
    return module.exports;
  }
});
`;

fs.writeFileSync(clientJsPath, bundle, 'utf8');
console.log(`Successfully built ${clientJsPath} (${bundle.length} bytes)`);
